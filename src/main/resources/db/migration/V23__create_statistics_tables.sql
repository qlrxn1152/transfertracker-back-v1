CREATE TABLE player_ranking (
    player_ranking_id BIGINT NOT NULL AUTO_INCREMENT,
    player_id BIGINT NOT NULL,
    league_code ENUM('EPL','LA_LIGA','BUNDESLIGA','SERIE_A','LIGUE_1','K_LEAGUE') NOT NULL,
    season INT NOT NULL,
    ranking_type ENUM('GOALS','ASSISTS') NOT NULL,
    ranking INT NULL,
    stat_value INT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (player_ranking_id),
    CONSTRAINT uk_player_ranking_key UNIQUE (player_id, league_code, season, ranking_type),
    CONSTRAINT fk_player_ranking_player FOREIGN KEY (player_id) REFERENCES player (player_id)
);
