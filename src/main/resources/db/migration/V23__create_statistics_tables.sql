CREATE TABLE fixture_statistics (
    fixture_statistics_id BIGINT NOT NULL AUTO_INCREMENT,
    fixture_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    passes_accurate INT NULL,
    shots_inside_box INT NULL,
    shots_outside_box INT NULL,
    blocked_shots INT NULL,
    free_kicks INT NULL,
    shots_on_goal INT NULL,
    goalkeeper_saves INT NULL,
    shots_off_goal INT NULL,
    total_passes INT NULL,
    total_shots INT NULL,
    yellow_cards INT NULL,
    corner_kicks INT NULL,
    offsides INT NULL,
    fouls INT NULL,
    red_cards INT NULL,
    ball_possession INT NULL,
    expected_goals DECIMAL(12,6) NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (fixture_statistics_id),
    CONSTRAINT uk_fixture_statistics_key UNIQUE (fixture_id, team_id),
    CONSTRAINT fk_fixture_statistics_fixture FOREIGN KEY (fixture_id) REFERENCES fixture (fixture_id),
    CONSTRAINT fk_fixture_statistics_team FOREIGN KEY (team_id) REFERENCES team (team_id)
);

