package com.dhoon.transfertracker.internal.fixture.dto.record;
import com.dhoon.transfertracker.internal.fixture.domain.FixturePlayerStatistics;
import java.math.BigDecimal;
import java.time.Instant;
public record FixturePlayerStatisticsResponse(
        Long id,
        Long teamId,
        String teamName,
        Long playerId,
        String playerName,
        String photoUrl,
        Integer minutes,
        Integer number,
        String position,
        BigDecimal rating,
        Boolean captain,
        Integer shotsTotal,
        Integer shotsOn,
        Integer goals,
        Integer goalsConceded,
        Integer assists,
        Integer saves,
        Integer passesTotal,
        Integer passesKey,
        Integer tacklesTotal,
        Integer blocks,
        Integer interceptions,
        Integer duelsTotal,
        Integer duelsWon,
        Integer dribblesAttempts,
        Integer dribblesSuccess,
        Integer dribbledPast,
        Integer foulsDrawn,
        Integer foulsCommitted,
        Integer yellowCards,
        Integer redCards,
        Integer penaltyWon,
        Integer penaltyCommitted,
        Integer penaltyScored,
        Integer penaltyMissed,
        Integer penaltySaved,
        Boolean substitute,
        Integer offsides,
        Integer passesAccurate,
        Instant updatedAt
) {
    public static FixturePlayerStatisticsResponse from(FixturePlayerStatistics e) {
        return new FixturePlayerStatisticsResponse(
            e.getId(),
            e.getTeam().getId(),
            e.getTeam().getDisplayName(),
            e.getPlayer().getId(),
            e.getPlayer().getDisplayName(),
            "https://media.api-sports.io/football/players/" + e.getPlayer().getApiFootballId() + ".png",
            e.getMinutes(),
            e.getNumber(),
            e.getPosition(),
            e.getRating(),
            e.getCaptain(),
            e.getShotsTotal(),
            e.getShotsOn(),
            e.getGoals(),
            e.getGoalsConceded(),
            e.getAssists(),
            e.getSaves(),
            e.getPassesTotal(),
            e.getPassesKey(),
            e.getTacklesTotal(),
            e.getBlocks(),
            e.getInterceptions(),
            e.getDuelsTotal(),
            e.getDuelsWon(),
            e.getDribblesAttempts(),
            e.getDribblesSuccess(),
            e.getDribbledPast(),
            e.getFoulsDrawn(),
            e.getFoulsCommitted(),
            e.getYellowCards(),
            e.getRedCards(),
            e.getPenaltyWon(),
            e.getPenaltyCommitted(),
            e.getPenaltyScored(),
            e.getPenaltyMissed(),
            e.getPenaltySaved(),
            e.getSubstitute(),
            e.getOffsides(),
            e.getPassesAccurate(),
            e.getUpdatedAt()
        );
    }
}
