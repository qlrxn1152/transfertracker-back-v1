package com.dhoon.transfertracker.internal.player.dto.record;
import tools.jackson.databind.JsonNode;
import java.math.BigDecimal;

import com.dhoon.transfertracker.external.football.client.StatisticsJson;
public record ApiFootballPlayerSeasonStatisticsResponse(
        Long teamApiId,
        Long playerApiId,
        String playerName,
        Long leagueApiId,
        Integer season,
        Integer minutes,
        Integer number,
        String position,
        BigDecimal rating,
        Boolean captain,
        Integer shotsTotal,
        Integer shotsOn,
        Integer goals,
        Integer goalsConceded,
        Integer assists,
        Integer saves,
        Integer passesTotal,
        Integer passesKey,
        Integer tacklesTotal,
        Integer blocks,
        Integer interceptions,
        Integer duelsTotal,
        Integer duelsWon,
        Integer dribblesAttempts,
        Integer dribblesSuccess,
        Integer dribbledPast,
        Integer foulsDrawn,
        Integer foulsCommitted,
        Integer yellowCards,
        Integer redCards,
        Integer penaltyWon,
        Integer penaltyCommitted,
        Integer penaltyScored,
        Integer penaltyMissed,
        Integer penaltySaved,
        Integer appearances,
        Integer lineups,
        Integer substitutesIn,
        Integer substitutesOut,
        Integer substitutesBench,
        Integer yellowRedCards,
        Integer passesAccuracy
) {
    public static ApiFootballPlayerSeasonStatisticsResponse from(JsonNode team, JsonNode player, JsonNode stats) {
        return new ApiFootballPlayerSeasonStatisticsResponse(
            StatisticsJson.id(team.path("id")),
            StatisticsJson.id(player.path("id")),
            StatisticsJson.name(player.path("name")),
            StatisticsJson.id(stats.path("league").path("id")),
            StatisticsJson.integer(stats.path("league").path("season")),
            StatisticsJson.integer(stats.path("games").path("minutes")),
            StatisticsJson.integer(stats.path("games").path("number")),
            StatisticsJson.string(stats.path("games").path("position")),
            StatisticsJson.decimal(stats.path("games").path("rating")),
            StatisticsJson.bool(stats.path("games").path("captain")),
            StatisticsJson.integer(stats.path("shots").path("total")),
            StatisticsJson.integer(stats.path("shots").path("on")),
            StatisticsJson.integer(stats.path("goals").path("total")),
            StatisticsJson.integer(stats.path("goals").path("conceded")),
            StatisticsJson.integer(stats.path("goals").path("assists")),
            StatisticsJson.integer(stats.path("goals").path("saves")),
            StatisticsJson.integer(stats.path("passes").path("total")),
            StatisticsJson.integer(stats.path("passes").path("key")),
            StatisticsJson.integer(stats.path("tackles").path("total")),
            StatisticsJson.integer(stats.path("tackles").path("blocks")),
            StatisticsJson.integer(stats.path("tackles").path("interceptions")),
            StatisticsJson.integer(stats.path("duels").path("total")),
            StatisticsJson.integer(stats.path("duels").path("won")),
            StatisticsJson.integer(stats.path("dribbles").path("attempts")),
            StatisticsJson.integer(stats.path("dribbles").path("success")),
            StatisticsJson.integer(stats.path("dribbles").path("past")),
            StatisticsJson.integer(stats.path("fouls").path("drawn")),
            StatisticsJson.integer(stats.path("fouls").path("committed")),
            StatisticsJson.integer(stats.path("cards").path("yellow")),
            StatisticsJson.integer(stats.path("cards").path("red")),
            StatisticsJson.integer(stats.path("penalty").path("won")),
            StatisticsJson.integer(stats.path("penalty").path("commited")),
            StatisticsJson.integer(stats.path("penalty").path("scored")),
            StatisticsJson.integer(stats.path("penalty").path("missed")),
            StatisticsJson.integer(stats.path("penalty").path("saved")),
            StatisticsJson.integer(stats.path("games").path("appearences")),
            StatisticsJson.integer(stats.path("games").path("lineups")),
            StatisticsJson.integer(stats.path("substitutes").path("in")),
            StatisticsJson.integer(stats.path("substitutes").path("out")),
            StatisticsJson.integer(stats.path("substitutes").path("bench")),
            StatisticsJson.integer(stats.path("cards").path("yellowred")),
            StatisticsJson.integer(stats.path("passes").path("accuracy"))
        );
    }
}
